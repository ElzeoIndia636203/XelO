import type { ReactNode } from 'react';

export function formatDigitalReportNotice({
  facultyName,
  timestamp,
  universityName,
}: {
  facultyName: string;
  timestamp: string;
  universityName: string;
}): string {
  const faculty = facultyName.trim() || 'Course Faculty';
  const university = universityName.trim() || 'University';
  return `This report is digitally generated by ${faculty} on ${timestamp} in XeIO, revolutionary AI-enabled LMS of ${university}. No signatures required.`;
}

export function DigitalReportFooter({
  facultyName,
  timestamp,
  universityName,
  inlineOnly = false,
}: {
  facultyName: string;
  timestamp: string;
  universityName: string;
  inlineOnly?: boolean;
}) {
  const notice = formatDigitalReportNotice({ facultyName, timestamp, universityName });

  return (
    <>
      <div className={inlineOnly ? 'report-footer-inline no-print' : 'report-footer-inline no-print'}>
        {notice}
      </div>
      {!inlineOnly ? <div className="report-print-footer print-only">{notice}</div> : null}
    </>
  );
}

export function PrintableReportFrame({
  facultyName,
  timestamp,
  universityName,
  officialTitle,
  officialSubtitle,
  children,
}: {
  facultyName: string;
  timestamp: string;
  universityName: string;
  officialTitle?: string;
  officialSubtitle?: string;
  children: ReactNode;
}) {
  const notice = formatDigitalReportNotice({ facultyName, timestamp, universityName });

  return (
    <div className="printable-report-root">
      {officialTitle ? (
        <div className="print-only print-official-header">
          <div className="print-official-uni">{universityName || 'University'}</div>
          <div className="print-official-title">{officialTitle}</div>
          {officialSubtitle ? <div className="print-official-sub">{officialSubtitle}</div> : null}
        </div>
      ) : null}

      <table className="print-page-table">
        <tbody>
          <tr>
            <td>{children}</td>
          </tr>
        </tbody>
        <tfoot>
          <tr>
            <td>
              <div className="print-footer-space" aria-hidden="true" />
            </td>
          </tr>
        </tfoot>
      </table>

      <div className="report-footer-inline no-print">{notice}</div>
      <div className="report-print-footer print-only">{notice}</div>
    </div>
  );
}
